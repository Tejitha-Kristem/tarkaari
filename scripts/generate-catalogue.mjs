// Writes supabase/seed.sql and public/veg/<slug>.svg from scripts/catalogue.mjs.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { catalogue } from "./catalogue.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

mkdirSync(`${root}public/veg`, { recursive: true });
// A real photo (added with `npm run photo`) wins over the placeholder.
const photoFor = (slug) => (existsSync(`${root}public/veg/${slug}.webp`) ? `/veg/${slug}.webp` : `/veg/${slug}.svg`);

for (const [slug] of catalogue) {
  // Neutral stand-in until a real photo is added.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" role="img">
  <rect width="256" height="256" fill="#f2f2f0"/>
  <g fill="none" stroke="#c9c9c4" stroke-width="8" stroke-linecap="round" stroke-linejoin="round">
    <rect x="78" y="88" width="100" height="80" rx="12"/>
    <circle cx="128" cy="128" r="20"/>
    <path d="M108 88l8-14h24l8 14"/>
  </g>
</svg>
`;
  writeFileSync(`${root}public/veg/${slug}.svg`, svg);
}

const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;
const rows = catalogue.map(
  ([slug, en, kn, unit, category, aliases], i) =>
    `  (${q(slug)}, ${q(en)}, ${q(kn)}, ${q(photoFor(slug))}, ${q(unit)}, ${q(category)}, ${(i + 1) * 10}, ${arr(aliases)})`,
);

const sql = `-- Generated by scripts/generate-catalogue.mjs from scripts/catalogue.mjs. Do not edit by hand.
-- Safe to run repeatedly: existing items (matched by slug) are updated in place.

insert into public.catalogue_items (slug, name_en, name_kn, photo, default_unit, category, sort_order, aliases)
values
${rows.join(",\n")}
on conflict (slug) do update set
  name_en = excluded.name_en,
  name_kn = excluded.name_kn,
  photo = excluded.photo,
  default_unit = excluded.default_unit,
  category = excluded.category,
  sort_order = excluded.sort_order,
  aliases = excluded.aliases;
`;
writeFileSync(`${root}supabase/seed.sql`, sql);
console.log(`Wrote ${catalogue.length} catalogue items and pictures.`);
