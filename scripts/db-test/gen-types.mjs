// Generates src/types/database.ts (Supabase's format) from a plain Postgres
// database that has the migrations applied. Once a Supabase project exists you
// can use `npm run db:types` instead; both produce compatible output.
//
// Usage: PGHOST=... PGPORT=... PGUSER=postgres PGDATABASE=... node scripts/db-test/gen-types.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const sql = (query) =>
  JSON.parse(execFileSync("psql", ["-X", "-tA", "-c", `select coalesce(json_agg(t), '[]') from (${query}) t`]).toString());

const enums = sql(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as values
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

const columns = sql(`
  select c.relname as table, a.attname as name, format_type(a.atttypid, a.atttypmod) as type,
         t.typname as udt, t.typcategory as category, not a.attnotnull as nullable,
         a.atthasdef as has_default, a.attgenerated <> '' as generated, a.attnum
  from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
  join pg_type t on t.oid = a.atttypid
  where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`);

const fks = sql(`
  select con.conname as name, c.relname as table, rc.relname as ref_table,
         array(select attname from unnest(con.conkey) with ordinality k(n, i)
               join pg_attribute on attrelid = con.conrelid and attnum = k.n order by i) as columns,
         array(select attname from unnest(con.confkey) with ordinality k(n, i)
               join pg_attribute on attrelid = con.confrelid and attnum = k.n order by i) as ref_columns,
         exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('p', 'u')
                 and u.conkey::int[] @> con.conkey::int[] and u.conkey::int[] <@ con.conkey::int[]) as one_to_one
  from pg_constraint con join pg_class c on c.oid = con.conrelid join pg_class rc on rc.oid = con.confrelid
  join pg_namespace n on n.oid = c.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and rc.relnamespace = n.oid
  order by c.relname, con.conname`);

const functions = sql(`
  select p.proname as name, p.proretset as returns_set, rt.typname as return_type,
         coalesce(p.proargnames, '{}') as arg_names, coalesce(p.proargmodes::text[], '{}') as arg_modes,
         array(select format_type(x, null) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) x) as arg_types,
         array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(x, i)
               join pg_type t on t.oid = a.x order by i) as arg_udts,
         p.pronargdefaults as n_defaults, p.pronargs as n_in,
         p.prorettype::regtype::text as return_regtype
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
  order by p.proname`);

function tsType(udt, category) {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1), "")}[]`;
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(udt)) return "number";
  if (udt === "bool") return "boolean";
  if (udt === "json" || udt === "jsonb") return "Json";
  if (category === "A") return "unknown[]";
  return "string";
}

const tables = {};
for (const c of columns) (tables[c.table] ??= []).push(c);

const ind = (n) => "  ".repeat(n);
let out = `// Generated by scripts/db-test/gen-types.mjs. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [table, cols] of Object.entries(tables)) {
  const row = cols.map((c) => `${ind(5)}${c.name}: ${tsType(c.udt, c.category)}${c.nullable ? " | null" : ""};`);
  const insert = cols.map((c) =>
    c.generated
      ? `${ind(5)}${c.name}?: never;`
      : `${ind(5)}${c.name}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c.udt, c.category)}${c.nullable ? " | null" : ""};`,
  );
  const update = cols.map((c) =>
    c.generated ? `${ind(5)}${c.name}?: never;` : `${ind(5)}${c.name}?: ${tsType(c.udt, c.category)}${c.nullable ? " | null" : ""};`,
  );
  const rels = fks
    .filter((f) => f.table === table)
    .map(
      (f) => `${ind(5)}{
${ind(6)}foreignKeyName: "${f.name}";
${ind(6)}columns: [${f.columns.map((x) => `"${x}"`).join(", ")}];
${ind(6)}isOneToOne: ${f.one_to_one};
${ind(6)}referencedRelation: "${f.ref_table}";
${ind(6)}referencedColumns: [${f.ref_columns.map((x) => `"${x}"`).join(", ")}];
${ind(5)}},`,
    );
  out += `${ind(3)}${table}: {
${ind(4)}Row: {
${row.join("\n")}
${ind(4)}};
${ind(4)}Insert: {
${insert.join("\n")}
${ind(4)}};
${ind(4)}Update: {
${update.join("\n")}
${ind(4)}};
${ind(4)}Relationships: [${rels.length ? `\n${rels.join("\n")}\n${ind(4)}` : ""}];
${ind(3)}};
`;
}
out += `${ind(2)}};
${ind(2)}Views: { [_ in never]: never };
${ind(2)}Functions: {
`;
for (const f of functions) {
  const inArgs = [];
  const outCols = [];
  f.arg_names.forEach((name, i) => {
    const mode = f.arg_modes[i] ?? "i";
    const type = tsType(f.arg_udts[i], "");
    if (mode === "i" || mode === "b") inArgs.push({ name, type });
    if (mode === "t" || mode === "o" || mode === "b") outCols.push({ name, type });
  });
  const firstDefault = f.n_in - f.n_defaults;
  const args = inArgs.length
    ? `{ ${inArgs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${a.type}`).join("; ")} }`
    : "never";
  let ret;
  if (outCols.length) ret = `{ ${outCols.map((c) => `${c.name}: ${c.type}`).join("; ")} }[]`;
  else if (tables[f.return_type]) ret = `Database["public"]["Tables"]["${f.return_type}"]["Row"]${f.returns_set ? "[]" : ""}`;
  else ret = `${tsType(f.return_type, "")}${f.returns_set ? "[]" : ""}`;
  const setof = f.returns_set && tables[f.return_type]
    ? `\n${ind(4)}SetofOptions: { from: "*"; to: "${f.return_type}"; isOneToOne: false; isSetofReturn: true };`
    : "";
  out += `${ind(3)}${f.name}: {\n${ind(4)}Args: ${args};\n${ind(4)}Returns: ${ret};${setof}\n${ind(3)}};\n`;
}
out += `${ind(2)}};
${ind(2)}Enums: {
${enums.map((e) => `${ind(3)}${e.name}: ${e.values.map((v) => `"${v}"`).join(" | ")};`).join("\n")}
${ind(2)}};
${ind(2)}CompositeTypes: { [_ in never]: never };
${ind(1)}};
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];

export const Constants = {
  public: {
    Enums: {
${enums.map((e) => `${ind(3)}${e.name}: [${e.values.map((v) => `"${v}"`).join(", ")}],`).join("\n")}
    },
  },
} as const;
`;

const target = fileURLToPath(new URL("../../src/types/database.ts", import.meta.url));
writeFileSync(target, out);
console.log(`Wrote ${Object.keys(tables).length} tables, ${functions.length} functions, ${enums.length} enums.`);
