// Writes supabase/setup.sql: every migration plus the catalogue seed in one
// file, for pasting into Supabase → SQL Editor on a new project.
// Usage: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/", import.meta.url);
const files = readdirSync(new URL("migrations/", dir)).filter((f) => f.endsWith(".sql")).sort();
const parts = [
  `-- Tarkaari database setup: all migrations + catalogue seed (generated by scripts/bundle-sql.mjs).
-- Paste into Supabase → SQL Editor on a NEW project and press Run. Takes a few seconds.
-- Re-running on a project that already has the tables stops with a clear message and changes nothing.

do $$
begin
  if to_regclass('public.users') is not null then
    raise exception 'Tarkaari is already set up in this project (public.users exists). Nothing was changed.';
  end if;
end $$;
`,
  ...files.map((f) => `\n-- ===== ${f} =====\n` + readFileSync(new URL(`migrations/${f}`, dir), "utf8")),
  "\n-- ===== seed.sql =====\n" + readFileSync(new URL("seed.sql", dir), "utf8"),
];
writeFileSync(new URL("setup.sql", dir), parts.join("\n"));
console.log(`Wrote supabase/setup.sql from ${files.length} migrations + seed.`);
